"""Pre-renders the share image's text (app/source/share_image.c): app/source/share_font.h.

    python tools/share_font.py [font.ttf]

Default: assets/fonts/Inter.ttf (SIL OFL 1.1, see assets/fonts/OFL.txt). Run from the repo
root. Needs Pillow.

Sizes are for the 720x720 image:
- the title "3DS Achievements" as one image (Inter 700, capitals 45 px tall), kerning included;
- the game name: printable ASCII (Inter 600, capitals 33 px);
- the count: '/' and the digits (Inter 600, capitals 30 px).
Each glyph is an 8-bit coverage image placed from the pen and the baseline, with its
advance in 1/64 pixel.
"""
import sys

from PIL import Image, ImageDraw, ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else "assets/fonts/Inter.ttf"
OUT = "app/source/share_font.h"
SS = 4              # drawn at 4x and shrunk, so glyphs aren't snapped to whole pixels
TITLE = "3DS Achievements"


def load(cap, weight):
    """The font at a weight, sized so a capital H is cap pixels tall."""
    def at(size):
        font = ImageFont.truetype(FONT, size)
        try:
            axes = font.get_variation_axes()
            font.set_variation_by_axes([weight if a["name"] == b"Weight" else a["default"] for a in axes])
        except Exception:
            pass                    # a static font: its weight is in the file
        return font
    probe = at(400)
    cap400 = -probe.getbbox("H", anchor="ls")[1]
    return at(max(1, round(400 * cap / cap400)))


def glyph_set(cap, weight, first, last):
    """(glyphs, alpha): each glyph (x, y, w, h, adv64, off), x and y from the pen and the baseline."""
    font = load(cap * SS, weight)
    glyphs, alpha = [], bytearray()
    for code in range(first, last + 1):
        ch = chr(code)
        left, top, right, bottom = font.getbbox(ch, anchor="ls")
        x0, y0 = left // SS, top // SS              # floor (top is negative: above the baseline)
        x1, y1 = -(-right // SS), -(-bottom // SS)
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        advance = round(font.getlength(ch) * 64 / SS)
        if right > left and bottom > top:
            big = Image.new("L", (w * SS, h * SS))
            ImageDraw.Draw(big).text((-x0 * SS, -y0 * SS), ch, font=font, fill=255, anchor="ls")
            glyphs.append((x0, y0, w, h, advance, len(alpha)))
            alpha += big.reduce(SS).tobytes()
        else:
            glyphs.append((0, 0, 0, 0, advance, len(alpha)))
    return glyphs, alpha


def title_image(cap, weight):
    """(w, h, ascent, alpha): the whole title, ascent = rows above the baseline."""
    font = load(cap * SS, weight)
    left, top, right, bottom = font.getbbox(TITLE, anchor="ls")
    x0, y0 = left // SS, top // SS
    x1, y1 = -(-right // SS), -(-bottom // SS)
    w, h = x1 - x0, y1 - y0
    big = Image.new("L", (w * SS, h * SS))
    ImageDraw.Draw(big).text((-x0 * SS, -y0 * SS), TITLE, font=font, fill=255, anchor="ls")
    return w, h, -y0, big.reduce(SS).tobytes()


def array(name, data):
    lines = [f"__attribute__((unused)) static const unsigned char {name}[] = {{"]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
    return lines


out = [
    "// Generated by tools/share_font.py from Inter, Copyright 2016 The Inter Project Authors,",
    "// SIL Open Font License 1.1 (assets/fonts/OFL.txt). Don't edit by hand.",
    "#ifndef SHARE_FONT_H",
    "#define SHARE_FONT_H",
    "",
    "// x, y: where the image goes from the pen and the baseline (y < 0: above it); adv64: pen",
    "// advance in 1/64 px; off: start of the w x h coverage image (0-255) in the set's alpha array.",
    "typedef struct { signed char x, y; unsigned char w, h; unsigned short adv64; unsigned int off; } ShareGlyph;",
    "",
]

w, h, ascent, alpha = title_image(45, 700)
out += [f"// \"{TITLE}\", Inter 700, capitals 45 px: {w}x{h}, {ascent} rows above the baseline.",
        f"#define SHARE_TITLE_W       {w}",
        f"#define SHARE_TITLE_H       {h}",
        f"#define SHARE_TITLE_ASCENT  {ascent}"]
out += array("share_title_alpha", alpha) + [""]

for name, cap, weight, first, last, what in (("name", 33, 600, 32, 126, "printable ASCII"),
                                              ("count", 30, 600, 47, 57, "'/' and the digits")):
    glyphs, alpha = glyph_set(cap, weight, first, last)
    upper = name.upper()
    out += [f"// The {name}: {what}, Inter {weight}, capitals {cap} px, {len(alpha)} bytes of images.",
            f"#define SHARE_{upper}_FIRST  {first}",
            f"#define SHARE_{upper}_LAST   {last}",
            f"#define SHARE_{upper}_CAP    {cap}",
            f"__attribute__((unused)) static const ShareGlyph share_{name}_glyphs[{len(glyphs)}] = {{"]
    out += [f"    {{ {g[0]}, {g[1]}, {g[2]}, {g[3]}, {g[4]}, {g[5]} }}," for g in glyphs]
    out += ["};"] + array(f"share_{name}_alpha", alpha) + [""]

out += ["#endif", ""]
with open(OUT, "w", newline="\n") as f:
    f.write("\n".join(out))
print(OUT)
