"""Pre-renders the font (Inter) into smooth glyph images: app/source/font_inter.h.

    python tools/app_font.py [font.ttf] [weight]

Defaults: assets/fonts/Inter.ttf (SIL OFL 1.1, see assets/fonts/OFL.txt), weight 500.
Run from the repo root. Needs Pillow.

Two sets of printable ASCII (32-126): font13 for 13 px lines and font26 for 26 px lines.
Each glyph is an 8-bit coverage image placed from the top of its line, with its advance
in 1/64 pixel so text keeps the font's own spacing. The app (app/source/draw.c) uses both;
the tracker's banner and in-game list (sysmodule/tracker/source/overlay.c) use font13 only,
and the compiler leaves out the set a program doesn't use.
"""
import sys

from PIL import Image, ImageDraw, ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else "assets/fonts/Inter.ttf"
WEIGHT = int(sys.argv[2]) if len(sys.argv) > 2 else 500
OUT = "app/source/font_inter.h"

LINE = 13           # pixels per line at scale 1 (LINE_H in draw.h)
CAP = 0.69          # a capital letter is this much of a line tall
BASELINE = 0.77     # the baseline is this far down a line
SS = 4              # drawn at 4x and shrunk, so glyphs aren't snapped to whole pixels


def load(cap):
    """The font at the given weight, sized so a capital H is cap pixels tall."""
    def at(size):
        font = ImageFont.truetype(FONT, size)
        try:
            axes = font.get_variation_axes()
            font.set_variation_by_axes([WEIGHT if a["name"] == b"Weight" else a["default"] for a in axes])
        except Exception:
            pass                    # a static font: its weight is in the file
        return font
    probe = at(400)
    cap400 = -probe.getbbox("H", anchor="ls")[1]
    return at(max(1, round(400 * cap / cap400)))


sets = []
for line in (LINE, 2 * LINE):
    font = load(round(line * CAP) * SS)
    base = round(line * BASELINE) * SS
    glyphs, alpha = [], bytearray()
    for code in range(32, 127):
        ch = chr(code)
        left, top, right, bottom = font.getbbox(ch, anchor="ls")
        top, bottom = top + base, bottom + base     # from the top of the line
        x0, y0 = left // SS, top // SS
        x1, y1 = -(-right // SS), -(-bottom // SS)
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        advance = round(font.getlength(ch) * 64 / SS)
        if right > left and bottom > top:
            big = Image.new("L", (w * SS, h * SS))
            ImageDraw.Draw(big).text((-x0 * SS, base - y0 * SS), ch, font=font, fill=255, anchor="ls")
            glyphs.append((x0, y0, w, h, advance, len(alpha)))
            alpha += big.reduce(SS).tobytes()
        else:
            glyphs.append((0, 0, 0, 0, advance, len(alpha)))
    assert len(alpha) < 65536
    sets.append((line, glyphs, alpha))

with open(OUT, "w", newline="\n") as f:
    f.write("// Generated by tools/app_font.py from Inter (weight %d), Copyright 2016 The Inter Project\n" % WEIGHT)
    f.write("// Authors, SIL Open Font License 1.1 (assets/fonts/OFL.txt). Don't edit by hand.\n")
    f.write("#ifndef FONT_INTER_H\n#define FONT_INTER_H\n\n")
    f.write("// x, y: where the image goes from the pen and the top of the line; adv64: pen advance in\n")
    f.write("// 1/64 px; off: start of the w x h coverage image (0-255) in the set's alpha array.\n")
    f.write("typedef struct { signed char x, y; unsigned char w, h; unsigned short adv64, off; } FontGlyph;\n")
    for line, glyphs, alpha in sets:
        drawn = [g for g in glyphs if g[2] > 0]
        f.write("\n// %d px lines: %d bytes of images.\n" % (line, len(alpha)))
        f.write("#define FONT%d_MIN_X       %d      // leftmost image column, from the pen\n" % (line, min(g[0] for g in drawn)))
        f.write("#define FONT%d_MAX_RIGHT   %d      // past the rightmost image column, from the pen\n"
                % (line, max(g[0] + g[2] for g in drawn)))
        f.write("#define FONT%d_BOTTOM      %d      // past the lowest image row, from the top of the line\n"
                % (line, max(g[1] + g[3] for g in drawn)))
        f.write("__attribute__((unused)) static const FontGlyph font%d_glyphs[95] = {\n" % line)
        f.write("".join("    { %d, %d, %d, %d, %d, %d },\n" % g for g in glyphs))
        f.write("};\n__attribute__((unused)) static const unsigned char font%d_alpha[] = {\n" % line)
        for i in range(0, len(alpha), 24):
            f.write("    " + ",".join(str(b) for b in alpha[i:i + 24]) + ",\n")
        f.write("};\n")
    f.write("\n#endif\n")
print(OUT, "-", " + ".join("%d px %d bytes" % (line, len(alpha)) for line, _, alpha in sets))
