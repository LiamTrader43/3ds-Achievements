"""Draws the viewer app's trophy (no dependencies) and writes:

    app/icon.png            48x48 Homebrew Launcher icon
    app/source/trophy.h     the trophy for achievement rows, unlocked (gold) and
                            locked (grey), as 48x48 RGB565 in the SMDH tile order
                            Draw_Icon() reads, composited on black

Run from the repo root: python tools/app_icons.py
"""
import struct
import zlib

N = 48
SS = 4  # supersampling


def trophy(x, y):
    """Shape test in 48x48 units. Returns a colour or None."""
    gold, dark_gold = (255, 196, 40), (200, 140, 20)
    if 9 <= y <= 28:                                    # cup, wide at the top
        t = (y - 9) / 19.0
        half = 13 - 7 * t * t
        if abs(x - 24) <= half:
            return gold if x - 24 < half - 4 else dark_gold
    for cx in (10.5, 37.5):                             # handles
        d = ((x - cx) ** 2 + ((y - 15) * 1.2) ** 2) ** 0.5
        if 4.0 <= d <= 6.5 and abs(x - 24) > 11:
            return gold
    if 28 <= y <= 34 and abs(x - 24) <= 2.5:            # stem and base
        return dark_gold
    if 34 <= y <= 37 and abs(x - 24) <= 6:
        return gold
    if 37 <= y <= 41 and abs(x - 24) <= 10:
        return dark_gold
    return None


def background(x, y, top, bottom):
    """Rounded square, a vertical gradient from top to bottom colour."""
    r, m = 8, 1
    cx = min(max(x, m + r), N - m - r)
    cy = min(max(y, m + r), N - m - r)
    if (x - cx) ** 2 + (y - cy) ** 2 > r * r or x < m or y < m or x > N - m or y > N - m:
        return None
    t = y / N
    return tuple(int(a + (b - a) * t) for a, b in zip(top, bottom))


def render(top, bottom, grey=False, dark=False):
    """RGBA pixels, row by row."""
    pixels = []
    for py in range(N):
        for px in range(N):
            acc = [0, 0, 0, 0]
            for sy in range(SS):
                for sx in range(SS):
                    x, y = px + (sx + 0.5) / SS, py + (sy + 0.5) / SS
                    c = trophy(x, y)
                    if c is not None and grey:
                        v = (c[0] * 30 + c[1] * 59 + c[2] * 11) // 100
                        c = (v * 45 // 100,) * 3
                    if c is not None and dark:                  # dark trophy on a light background
                        c = (78, 52, 8) if c[0] == 255 else (52, 34, 4)
                    if c is None:
                        c = background(x, y, top, bottom)
                    if c is not None:
                        acc[0] += c[0]; acc[1] += c[1]; acc[2] += c[2]; acc[3] += 255
            a = acc[3] // (SS * SS)
            k = max(acc[3] // 255, 1)
            pixels.append((acc[0] // k, acc[1] // k, acc[2] // k, a))
    return pixels


def png(pixels, path):
    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    rows = b"".join(b"\0" + b"".join(bytes(p) for p in pixels[y * N:(y + 1) * N]) for y in range(N))
    open(path, "wb").write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", N, N, 8, 6, 0, 0, 0))
                           + chunk(b"IDAT", zlib.compress(rows, 9)) + chunk(b"IEND", b""))


def tiled565(pixels):
    """RGB565 on black, in 8x8 tiles with Z-order inside each tile (SMDH icon order)."""
    out = []
    for i in range(N * N):
        tile, inner = divmod(i, 64)
        x = (tile % 6) * 8 + ((inner & 1) | ((inner >> 1) & 2) | ((inner >> 2) & 4))
        y = (tile // 6) * 8 + (((inner >> 1) & 1) | ((inner >> 2) & 2) | ((inner >> 3) & 4))
        r, g, b, a = pixels[y * N + x]
        r, g, b = r * a // 255, g * a // 255, b * a // 255
        out.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
    return out


def c_array(name, values):
    lines = [", ".join("0x%04X" % v for v in values[i:i + 12]) for i in range(0, len(values), 12)]
    return "static const u16 %s[48 * 48] = {\n    %s,\n};\n" % (name, ",\n    ".join(lines))


unlocked = render((255, 228, 150), (252, 204, 90), dark=True)
locked = render((38, 38, 44), (52, 52, 60), grey=True)
png(unlocked, "app/icon.png")
open("app/source/trophy.h", "w").write(
    "// Generated by tools/app_icons.py: the achievement-row trophies (48x48 RGB565,\n"
    "// SMDH tile order, for Draw_Icon).\n#pragma once\n\n#include <3ds.h>\n\n"
    + c_array("TROPHY_UNLOCKED", tiled565(unlocked)) + "\n" + c_array("TROPHY_LOCKED", tiled565(locked)))
print("wrote app/icon.png, app/source/trophy.h")
